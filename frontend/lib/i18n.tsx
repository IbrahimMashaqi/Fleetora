type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  tMessage: (message: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function isLocale(value: string | undefined): value is Locale {
  return value === "en" || value === "ar";
}

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string {
  const template = locale === "ar" ? arabic[key] : english[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values?.[name];
    return value === undefined ? match : String(value);
  });
}

const englishMessageKeys = new Map<string, TranslationKey>(
  (Object.keys(english) as TranslationKey[])
    .filter((key) => english[key] === key)
    .map((key) => [key, key]),
);

export function translateMessage(locale: Locale, message: string): string {
  const key = englishMessageKeys.get(message);
  return key ? translate(locale, key) : message;
}

export function LocaleProvider({ initialLocale, children }: { initialLocale: Locale; children: ReactNode }) {
  const [locale, setCurrentLocale] = useState(initialLocale);
  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale(nextLocale) {
      setCurrentLocale(nextLocale);
      document.documentElement.lang = nextLocale;
      document.documentElement.dir = nextLocale === "ar" ? "rtl" : "ltr";
      document.cookie = `fleetora_locale=${nextLocale}; Path=/; Max-Age=31536000; SameSite=Lax${window.location.protocol === "https:" ? "; Secure" : ""}`;
    },
    t: (key, values) => translate(locale, key, values),
    tMessage: (message) => translateMessage(locale, message),
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used within LocaleProvider.");
  return context;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useLocale();

  return (
    <DropdownMenu dir={locale === "ar" ? "rtl" : "ltr"}>
      <DropdownMenuTrigger asChild>
        <Button variant="ghost" size="icon" aria-label={t("Language")} className="size-10 shrink-0 text-foreground hover:bg-secondary hover:text-foreground [&_svg]:size-5">
          <Globe aria-hidden="true" />
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" aria-label={t("Language")}>
        <DropdownMenuRadioGroup value={locale} onValueChange={value => { if (value === "ar" || value === "en") setLocale(value); }}>
          <DropdownMenuRadioItem value="en" lang="en" aria-label={t("Switch language to English")}>English</DropdownMenuRadioItem>
          <DropdownMenuRadioItem value="ar" lang="ar" aria-label={t("Switch language to Arabic")}>العربية</DropdownMenuRadioItem>
        </DropdownMenuRadioGroup>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
